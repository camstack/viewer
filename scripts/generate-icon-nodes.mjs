/**
 * Generate `src/lib/icon-nodes.generated.ts`: the drawing data (lucide "icon
 * nodes") for EXACTLY the keys of the `@camstack/types` icon catalog, read from
 * the installed `lucide-react-native` per-icon modules.
 *
 * Why data and not 1,684 imports: a stored icon key can be any catalog key, and
 * Metro cannot tree-shake — one import per icon is 1,684 modules in the bundle.
 * The nodes are a few hundred KB of plain strings; `CatalogIcon` draws them.
 *
 * Run `npm run gen:icon-nodes` after a catalog or lucide bump, commit the
 * output. `icon-nodes.spec.ts` fails when a catalog key has no node data.
 */
import * as fs from 'node:fs'
import * as path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const { ICON_KEYS, ICON_VIEWER_MODULES } = require('@camstack/types/client')
const ICONS_DIR = path.join(ROOT, 'node_modules/lucide-react-native/dist/esm/icons')
const lucideVersion = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'node_modules/lucide-react-native/package.json'), 'utf8'),
).version

const SHAPES = new Set(['path', 'circle', 'ellipse', 'line', 'polygon', 'polyline', 'rect'])

function readNode(moduleName) {
  const src = fs.readFileSync(path.join(ICONS_DIR, `${moduleName}.mjs`), 'utf8')
  const start = src.indexOf('createLucideIcon(')
  const open = src.indexOf('[', start)
  const end = src.lastIndexOf(']);')
  if (start < 0 || open < 0 || end < 0) throw new Error(`unparseable icon module ${moduleName}`)
  // Trusted input: the installed lucide package, evaluated as a literal.
  const nodes = new Function(`return ${src.slice(open, end + 1)}`)()
  return nodes.map(([tag, attrs]) => {
    if (!SHAPES.has(tag)) throw new Error(`${moduleName}: unsupported element <${tag}>`)
    const { key: _drop, ...rest } = attrs
    return [tag, rest]
  })
}

const body = ICON_KEYS.map((key) => {
  const moduleName = ICON_VIEWER_MODULES[key] ?? key
  return `  ${JSON.stringify(key)}: ${JSON.stringify(readNode(moduleName))},`
}).join('\n')

const out = `/**
 * GENERATED by scripts/generate-icon-nodes.mjs from lucide-react-native@${lucideVersion}
 * for exactly the keys of the @camstack/types icon catalog. Do not edit.
 */
import type { IconKey } from '@camstack/types'

export type IconShapeTag = 'path' | 'circle' | 'ellipse' | 'line' | 'polygon' | 'polyline' | 'rect'
export type IconShapeAttrs = Readonly<Record<string, string | number>>
export type IconNode = readonly (readonly [IconShapeTag, IconShapeAttrs])[]

export const ICON_NODES: Readonly<Record<IconKey, IconNode>> = {
${body}
}
`
fs.writeFileSync(path.join(ROOT, 'src/lib/icon-nodes.generated.ts'), out)
console.log(`wrote ${ICON_KEYS.length} icons, ${(out.length / 1024).toFixed(0)} KB`)
